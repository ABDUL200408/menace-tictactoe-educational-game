    @staticmethod
    def _friendly_join(items: list[str]) -> str:
        """Join short learner-facing labels using natural English."""
        cleaned = [str(item).strip() for item in items if str(item).strip()]
        if not cleaned:
            return ""
        if len(cleaned) == 1:
            return cleaned[0]
        if len(cleaned) == 2:
            return f"{cleaned[0]} and {cleaned[1]}"
        return ", ".join(cleaned[:-1]) + f", and {cleaned[-1]}"

    def _simple_result_update_sentence(self) -> str:
        """Return one short sentence linking the final result to bead changes."""
        result = st.session_state.get(SessionKey.LAST_GAME_RESULT)
        rows = st.session_state.get(SessionKey.LAST_BEAD_CHANGES, [])
        labels = [
            self._move_label(int(row["original_move"]))
            for row in rows
            if row.get("original_move") is not None
        ]
        square_text = self._friendly_join(labels)
        if not result:
            return ""
        if result == "win":
            return (
                f"Because MENACE won, it increased the beads for squares {square_text}."
                if square_text else
                "Because MENACE won, it increased the beads for its helpful moves."
            )
        if result == "loss":
            return (
                f"Because MENACE lost, it reduced the beads for squares {square_text}."
                if square_text else
                "Because MENACE lost, it may lose a bead for some moves."
            )
        return (
            f"Because the game was a draw, it made smaller bead changes for squares {square_text}."
            if square_text else
            "Because the game was a draw, the bead changes were smaller."
        )

    def _refresh_decision_records_after_learning(self) -> None:
        """Synchronise stored move snapshots with current post-learning bead counts."""
        menace = st.session_state[SessionKey.MENACE]
        refreshed: list[dict[str, Any]] = []
        for original_record in st.session_state.get(SessionKey.SYMMETRY_MAPPINGS, []):
            record = dict(original_record)
            state = record.get("matchbox_state")
            box = menace.matchboxes.get(str(state)) if state is not None else None
            rows = [dict(row) for row in record.get("probability_rows", [])]
            if box is not None and rows:
                probabilities = box.probabilities()
                for row in rows:
                    move = int(row["matchbox_move"])
                    if move in box.beads:
                        row["beads"] = int(box.beads[move])
                        row["probability"] = float(probabilities.get(move, 0.0))
                record["probability_rows"] = rows
            refreshed.append(record)
        st.session_state[SessionKey.SYMMETRY_MAPPINGS] = refreshed

    @staticmethod
    def _hardest_opponent_types(grouped: pd.DataFrame) -> list[str]:
        """Return every opponent tied for the lowest MENACE win rate."""
        if grouped.empty:
            return []
        minimum = float(grouped["win_rate"].min())
        return [
            str(value)
            for value in grouped.loc[
                grouped["win_rate"].sub(minimum).abs() < 1e-12,
                "opponent_type",
            ].tolist()
        ]

    def _render_simple_evidence_panel(self, page: str) -> None:
        """
        Show learner-friendly evidence for the current page.

        The panel uses the current session data and keeps detailed tables and
        research terminology inside a collapsed optional section.
        """
        titles = {
            "play": "Evidence from this game",
            "training": "Evidence from this practice run",
            "comparison": "Evidence from the opponent challenge",
            "results": "Graphs from the latest practice run",
            "learning": "Evidence inside MENACE's memory",
        }
        title = titles.get(page, "See the evidence")

        with st.expander(f"📊 {title}", expanded=False):
            st.caption(
                "This optional section presents the same underlying evidence with clear "
                "labels. Teachers, parents, and curious learners can open it "
                "without changing MENACE."
            )

            if page == "play":
                board = st.session_state[SessionKey.BOARD]
                cells = [
                    value if value != Board.EMPTY else self._square_label(index)
                    for index, value in enumerate(board.cells)
                ]
                st.markdown("**Current board evidence**")
                st.dataframe(
                    pd.DataFrame(
                        [cells[0:3], cells[3:6], cells[6:9]],
                        columns=["Left", "Middle", "Right"],
                        index=["Top", "Centre", "Bottom"],
                    ),
                    width="stretch",
                )

                latest = self._latest_symmetry_mapping_record()
                if latest is not None:
                    rows = latest.get("probability_rows", [])
                    if rows:
                        evidence = pd.DataFrame(rows)
                        rename = {
                            "original_board_square": "Square",
                            "beads": "Beads",
                            "probability": "Chance",
                            "selected": "Chosen",
                        }
                        keep = [column for column in rename if column in evidence.columns]
                        evidence = evidence[keep].rename(columns=rename)
                        if "Square" in evidence.columns:
                            evidence["Square"] = evidence["Square"].map(
                                lambda value: self._square_label(int(value))
                            )
                        if "Chance" in evidence.columns:
                            evidence["Chance"] = evidence["Chance"].map(
                                lambda value: f"{float(value):.1%}"
                            )
                        st.markdown("**Latest MENACE choice evidence**")
                        st.dataframe(evidence, width="stretch", hide_index=True)
                else:
                    st.info(
                        "Play until MENACE moves to create choice evidence."
                    )
                return

            if page in {"training", "results"}:
                history = self._normalise_history(
                    st.session_state.get(SessionKey.HISTORY, pd.DataFrame())
                )
                if history.empty:
                    st.info(
                        "Give MENACE some practice first. The learning graphs will "
                        "appear here afterwards."
                    )
                    return

                tracker = StatisticsTracker(history)
                summary = tracker.summary()
                latest = history.iloc[-1]
                cols = st.columns(4)
                cols[0].metric("Games", f"{int(latest['game']):,}")
                cols[1].metric("MENACE wins", f"{int(latest['menace_wins']):,}")
                cols[2].metric("Draws", f"{int(latest['draws']):,}")
                cols[3].metric("Win rate", f"{float(summary.win_rate):.1%}")

                figures = self.visualiser.training_dashboard_figures(history)
                preferred = [
                    ("learning_curve", "How MENACE's results changed"),
                    ("rolling_learning_curve", "Smoothed practice progress"),
                    ("outcome_rates", "Wins, draws, and opponent wins"),
                ]
                shown = 0
                for key, friendly_title in preferred:
                    figure = figures.get(key)
                    if figure is None:
                        continue
                    st.markdown(f"**{friendly_title}**")
                    self._render_exportable_figure(
                        figure,
                        name=f"{page}_{key}",
                        chart_key=f"simple_evidence_{page}_{key}",
                    )
                    shown += 1
                    if shown >= (2 if page == "results" else 1):
                        break

                st.download_button(
                    "Download the practice evidence (CSV)",
                    data=Trainer.evidence_frame(history).to_csv(index=False),
                    file_name="training_evidence.csv",
                    mime="text/csv",
                    key=f"simple_{page}_training_csv",
                )
                st.download_button(
                    "Download all practice graphs and images (ZIP)",
                    data=self._figure_download_zip(
                        figures,
                        evidence_name="practice",
                    ),
                    file_name="menace_practice_figures.zip",
                    mime="application/zip",
                    key=f"simple_{page}_training_figures_zip",
                    help=(
                        "Downloads interactive HTML graphs and report-ready PNG "
                        "images from the latest practice round."
                    ),
                )
                return

            if page == "comparison":
                results = st.session_state.get(
                    SessionKey.COMPARISON,
                    pd.DataFrame(),
                )
                if results is None or results.empty:
                    st.info(
                        "Run the opponent challenge first. Its evidence will appear "
                        "here afterwards."
                    )
                    return

                comparator = OpponentComparator(results)
                rows = comparator.evaluation_rows()
                if rows.empty:
                    st.info("No completed opponent-test rows were found.")
                    return

                grouped = (
                    rows.groupby("opponent_type", as_index=False)
                    .agg(
                        Games=("games", "sum"),
                        MENACE_Wins=("menace_wins", "sum"),
                        Draws=("draws", "sum"),
                        Opponent_Wins=("opponent_wins", "sum"),
                    )
                )
                grouped["MENACE Win Rate"] = (
                    grouped["MENACE_Wins"] / grouped["Games"]
                ).map(lambda value: f"{float(value):.1%}")
                grouped = grouped.rename(
                    columns={
                        "opponent_type": "Opponent",
                        "MENACE_Wins": "MENACE wins",
                        "Opponent_Wins": "Opponent wins",
                    }
                )
                friendly_opponents = {
                    "Random": "The Guesser (Random)",
                    "Heuristic": "The Rule Follower (Heuristic)",
                    "Minimax": "The Careful Thinker (Minimax)",
                }
                grouped["Opponent"] = grouped["Opponent"].map(
                    lambda value: friendly_opponents.get(str(value), str(value))
                )
                st.dataframe(grouped, width="stretch", hide_index=True)
                st.download_button(
                    "Download the comparison evidence (CSV)",
                    data=Trainer.evidence_frame(results).to_csv(index=False),
                    file_name="comparison_evidence.csv",
                    mime="text/csv",
                    key="simple_comparison_evidence_csv",
                )
                comparison_figures = self.visualiser.comparison_dashboard_figures(
                    results
                )
                st.download_button(
                    "Download all comparison graphs and images (ZIP)",
                    data=self._figure_download_zip(
                        comparison_figures,
                        evidence_name="comparison",
                    ),
                    file_name="menace_comparison_figures.zip",
                    mime="application/zip",
                    key="simple_comparison_figures_zip",
                    help=(
                        "Downloads interactive HTML graphs and report-ready PNG "
                        "images from the opponent challenge."
                    ),
                )
                return

            if page == "learning":
                menace = st.session_state[SessionKey.MENACE]
                matchboxes = len(getattr(menace, "matchboxes", {}))
                total_beads = sum(
                    sum(box.beads.values())
                    for box in getattr(menace, "matchboxes", {}).values()
                )
                cols = st.columns(3)
                cols[0].metric(
                    "Practice games completed",
                    f"{int(getattr(menace, 'games_played', 0)):,}",
                )
                cols[1].metric("Matchboxes", f"{matchboxes:,}")
                cols[2].metric("Beads", f"{total_beads:,}")

                matchbox = self._current_matchbox()
                if matchbox is not None:
                    st.markdown("**Current bead probabilities**")
                    try:
                        self._render_exportable_figure(
                            self.visualiser.matchbox_probabilities(matchbox),
                            name="current_matchbox_probabilities",
                            chart_key="simple_learning_evidence_probability",
                        )
                    except Exception:
                        st.dataframe(
                            pd.DataFrame(
                                [
                                    {
                                        "Square": self._square_label(move),
                                        "Beads": beads,
                                        "Chance": (
                                            f"{matchbox.probabilities().get(move, 0.0):.1%}"
                                        ),
                                    }
                                    for move, beads in sorted(matchbox.beads.items())
                                ]
                            ),
                            width="stretch",
                            hide_index=True,
                        )
                else:
                    st.info(
                        "Play one move first to create a current matchbox example."
                    )
                return

