    def _square_label(self, index: int) -> str:
        """Map internal board indexes 0-8 to learner-facing labels A-I."""
        Board.validate_move_index(index)
        return self.config.project_config.education.square_label(index)

    def _move_label(self, index: Optional[int]) -> str:
        """Return a safe learner-facing square label."""
        return '?' if index is None else self._square_label(int(index))

    def _letterise_play_text(self, value: Any) -> str:
        """
        Convert Play-page move references from internal indexes 0–8 to A–I.

        The conversion is presentation-only. It handles explicit move/square/index
        phrases and the three move lists generated by MENACE/Board explanations:
        Available moves, Legal original-board moves, and Legal matchbox moves.
        State strings, counts, probabilities, bead values and the internal model
        remain unchanged.
        """
        text = str(value)

        def replace_reference(match: re.Match[str]) -> str:
            prefix = match.group(1)
            index = int(match.group(2))
            return f"{prefix}{self._move_label(index)}"

        text = re.sub(
            r"(?i)\b((?:original |visible |board |canonical |matchbox )?"
            r"(?:square|move|index)(?:\s+|\s*[:=]\s*))([0-8])\b",
            replace_reference,
            text,
        )

        def replace_move_list(match: re.Match[str]) -> str:
            label = match.group(1)
            raw_items = match.group(2)
            indexes = re.findall(r"\b[0-8]\b", raw_items)
            letters = ", ".join(
                self._move_label(int(index)) for index in indexes
            )
            return f"{label}[{letters}]"

        return re.sub(
            r"(?i)\b("
            r"Available moves:\s*|"
            r"Legal original-board moves were:\s*|"
            r"Legal matchbox moves were:\s*"
            r")\[([^\]]*)\]",
            replace_move_list,
            text,
        )

    def _lettered_board_text(self, board: Board) -> str:
        """Return a three-row board using A–I for empty squares."""
        cells = [
            value if value != Board.EMPTY else self._square_label(index)
            for index, value in enumerate(board.cells)
        ]
        return "\n".join(
            " | ".join(cells[start:start + 3])
            for start in range(0, Board.BOARD_SIZE, 3)
        )

    def _letterise_matchbox_figure(self, figure: Any) -> Any:
        """Relabel Play-page chart move axes from 0–8 to A–I."""
        for trace in getattr(figure, "data", []):
            values = getattr(trace, "x", None)
            if values is None:
                continue
            converted = []
            changed = False
            for value in values:
                try:
                    index = int(value)
                except (TypeError, ValueError):
                    converted.append(value)
                    continue
                if 0 <= index < Board.BOARD_SIZE and str(value).strip() == str(index):
                    converted.append(self._move_label(index))
                    changed = True
                else:
                    converted.append(value)
            if changed:
                trace.x = converted
        return figure

    def _notify(self, message: str, icon: str = '💡') -> None:
        """Show a short message when the installed Streamlit version supports toast."""
        toast = getattr(st, 'toast', None)
        if callable(toast):
            toast(message, icon=icon)

    def _render_exportable_figure(
        self,
        figure: Any,
        *,
        name: str,
        chart_key: str,
    ) -> None:
        """Render one Plotly figure with a dedicated export button below it.

        HTML is always written because it preserves the interactive chart.  A
        report-ready PNG is written alongside it when Kaleido is available.
        Both files use the Visualiser's validated ``results/figures`` path.
        """
        # Keep exported figures report-ready (white background), but render a
        # separate copy in Streamlit so the chart follows the active Light/Dark
        # app theme. The trace colours are left untouched.
        display_figure = copy.deepcopy(figure)
        if hasattr(display_figure, "update_layout"):
            display_figure.update_layout(
                template=None,
                paper_bgcolor="rgba(0,0,0,0)",
                plot_bgcolor="rgba(0,0,0,0)",
            )
            layout = getattr(display_figure, "layout", None)
            if layout is not None:
                if getattr(layout, "font", None) is not None:
                    layout.font.color = None
                title = getattr(layout, "title", None)
                if title is not None and getattr(title, "font", None) is not None:
                    title.font.color = None

                # The export theme deliberately fixes light-mode axis colours.
                # Clear only those presentation colours on the display copy so
                # Streamlit can provide suitable values for the active theme.
                layout_keys = list(layout.to_plotly_json().keys())
                for axis_name in layout_keys:
                    if not (axis_name.startswith("xaxis") or axis_name.startswith("yaxis")):
                        continue
                    axis = getattr(layout, axis_name, None)
                    if axis is None:
                        continue
                    axis.gridcolor = None
                    axis.zerolinecolor = None
                    axis.linecolor = None
                    if getattr(axis, "tickfont", None) is not None:
                        axis.tickfont.color = None
                    if getattr(axis, "title", None) is not None and getattr(axis.title, "font", None) is not None:
                        axis.title.font.color = None

        st.plotly_chart(
            display_figure,
            width="stretch",
            key=chart_key,
            theme="streamlit",
        )
        evidence_purpose = {
            "learning_curve": "Evidence of how win, loss and draw rates changed during training.",
            "rolling_learning_curve": "A smoothed view that makes the overall learning trend easier to interpret.",
            "outcome_counts": "The exact final number of wins, losses and draws.",
            "outcome_rates": "The final outcome proportions, useful for a concise results summary.",
            "early_late_comparison": "Direct evidence comparing behaviour near the start and end of training.",
            "matchbox_growth": "Evidence of how MENACE's canonical-state memory expanded during training.",
            "comparison_rates": "A complete win, loss and draw comparison across all opponent types.",
            "comparison_win_rate": "A focused comparison of MENACE's success against each opponent.",
            "comparison_loss_rate": "Evidence identifying the opponents that defeated MENACE most often.",
        }.get(name.removeprefix("results_").removeprefix("comparison_"))
        if evidence_purpose:
            st.caption(f"Report evidence: {evidence_purpose}")
        if not st.button(
            "🖼️ Export this figure",
            key=f"export_figure_{chart_key}",
            help=(
                "Save this graph as PNG and interactive HTML in "
                "results/figures."
            ),
        ):
            return

        safe_name = re.sub(r"[^A-Za-z0-9_.-]+", "_", name).strip("_")
        html_path = self.visualiser.export_figure_html(figure, safe_name)
        try:
            png_path = self.visualiser.export_figure_png(figure, safe_name)
        except Exception as exc:
            st.warning(
                f"Saved the interactive figure to {html_path}. PNG export was "
                f"not available: {exc}"
            )
            return

        st.success(
            "Figure exported successfully:\n\n"
            f"- PNG: `{png_path}`\n"
            f"- HTML: `{html_path}`"
        )

    def _figure_download_zip(
        self,
        figures: dict[str, Any],
        *,
        evidence_name: str,
    ) -> bytes:
        """Return report-ready Plotly HTML and PNG figures in one ZIP file."""
        buffer = BytesIO()
        png_failures: list[str] = []
        with ZipFile(buffer, "w", compression=ZIP_DEFLATED) as archive:
            for name, figure in figures.items():
                safe_name = re.sub(r"[^A-Za-z0-9_.-]+", "_", str(name)).strip("_")
                self.visualiser._apply_academic_theme(figure)
                archive.writestr(
                    f"html/{safe_name}.html",
                    figure.to_html(
                        include_plotlyjs="cdn",
                        full_html=True,
                        config={
                            "displaylogo": False,
                            "responsive": True,
                            "toImageButtonOptions": {"format": "png", "scale": 2},
                        },
                    ),
                )
                try:
                    archive.writestr(
                        f"png/{safe_name}.png",
                        figure.to_image(format="png", scale=2),
                    )
                except Exception:
                    png_failures.append(safe_name)

            note = [
                f"MENACE {evidence_name} figure bundle",
                "",
                "The html folder contains interactive graphs.",
                "The png folder contains report-ready images.",
            ]
            if png_failures:
                note.extend(
                    [
                        "",
                        "PNG creation was unavailable for: " + ", ".join(png_failures),
                        "The HTML versions are still included and can export PNG from their camera button.",
                    ]
                )
            archive.writestr("README.txt", "\n".join(note) + "\n")
        return buffer.getvalue()

