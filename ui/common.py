    def _normalise_history(self, history: pd.DataFrame) -> pd.DataFrame:
        """Return a copy of a training history with expected columns normalised."""
        df = history.copy()
        if 'opponent_wins' not in df.columns and 'random_wins' in df.columns:
            df['opponent_wins'] = df['random_wins']
        if 'random_wins' not in df.columns and 'opponent_wins' in df.columns:
            df['random_wins'] = df['opponent_wins']
        return df

