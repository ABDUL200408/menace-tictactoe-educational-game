    def _latest_symmetry_mapping_record(self) -> Optional[dict[str, Any]]:
        """Return the latest stored MENACE symmetry-mapping record, if present."""
        mappings = st.session_state.get(SessionKey.SYMMETRY_MAPPINGS, [])
